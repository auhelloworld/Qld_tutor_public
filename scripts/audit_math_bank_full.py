def strip_latex(text: str) -> str:
    """Remove LaTeX markup for comparison purposes."""
    t = re.sub(r"\\text\{([^}]*)\}", r"\1", text)
    t = re.sub(r"\\mathrm\{([^}]*)\}", r"\1", t)
    t = re.sub(r"\\[a-zA-Z]+(\{[^}]*\})*", "", t)
    t = t.replace("$", "").replace("\\", "")
    return t.strip()


def extract_numbers(text: str) -> list[float]:
    """Extract all numeric values from text, including LaTeX fractions."""
    numbers: list[float] = []
    # LaTeX fractions: \frac{num}{den} or \dfrac{num}{den}
    for m in re.finditer(r"\\d?frac\{([^}]+)\}\{([^}]+)\}", text):
        try:
            numbers.append(float(m.group(1)) / float(m.group(2)))
        except (ValueError, ZeroDivisionError):
            pass
    # Remove LaTeX notation for standard number extraction
    cleaned = re.sub(r"\\[a-zA-Z]+(\{[^}]*\})*", " ", text)
    cleaned = cleaned.replace("$", " ").replace("{", " ").replace("}", " ")
    # Signed numbers: -5, +3
    for m in re.finditer(r"[+-]?\d+(?:\.\d+)?", cleaned):
        try:
            numbers.append(float(m.group(0)))
        except ValueError:
            pass
    return numbers


def extract_integers(text: str) -> list[int]:
    """Extract integer values from text."""
    nums = extract_numbers(text)
    return [int(n) for n in nums if n == int(n)]


def extract_fractions(text: str) -> list[Fraction]:
    """Extract fractions from text."""
    fracs: list[Fraction] = []
    # LaTeX fraction: \frac{a}{b} or \dfrac{a}{b}
    for m in re.finditer(r"\\d?frac\{([^}]+)\}\{([^}]+)\}", text):
        try:
            num = int(m.group(1).strip())
            den = int(m.group(2).strip())
            fracs.append(Fraction(num, den))
        except (ValueError, ZeroDivisionError):
            pass
    # Plain fractions: a/b
    for m in re.finditer(r"(\d+)\s*/\s*(\d+)", text):
        try:
            fracs.append(Fraction(int(m.group(1)), int(m.group(2))))
        except (ValueError, ZeroDivisionError):
            pass
    return fracs


def safe_normalise(text: str) -> str:
    """Normalise text for comparison: lowercase, strip LaTeX, collapse whitespace."""
    t = strip_latex(text)
    t = t.lower().strip()
    t = re.sub(r"\s+", " ", t)
    t = t.replace("\\\\", "").replace("\\", "")
    # remove trailing punctuation
    t = t.rstrip(".,;:!?\"'€$%")
    return t.strip()


def mcq_answer_matches_choice(ex: dict[str, Any]) -> bool:
    """Check if answer matches the correct choice in an MCQ, with false-positive prevention.

    Specifically: answer "15" must NOT match choice text "5" via substring.
    """
    choices = ex.get("choices", [])
    correct_letter = str(ex.get("correct_choice", "")).upper().strip()
    answer = str(ex.get("answer", "")).strip()

    if not isinstance(choices, list) or len(choices) < 2:
        return False
    if correct_letter not in VALID_CHOICES:
        return False

    idx = ord(correct_letter) - ord("A")
    if idx < 0 or idx >= len(choices):
        return False
    chosen = str(choices[idx]).strip()

    # Direct letter match
    if answer.upper() == correct_letter:
        return True
    if re.search(rf"\bchoice\s+{re.escape(correct_letter)}\b", answer, flags=re.I):
        return True

    # Exact text match
    norm_ans = safe_normalise(answer)
    norm_chosen = safe_normalise(chosen)
    if norm_ans == norm_chosen:
        return True

    # Choice with prefix "A. value" vs plain answer
    stripped = re.sub(r"^[A-Z]\s*[\).:-]\s*", "", chosen, flags=re.I).strip()
    norm_stripped = safe_normalise(stripped)
    if norm_ans == norm_stripped:
        return True
    if norm_stripped and len(norm_stripped) >= 3 and norm_stripped in norm_ans:
        return True

    # Substring match with word-boundary checking to prevent "15" matching "5"
    # Only allow word-level matching, not partial numeric matching
    if norm_stripped:
        # Check if answer and stripped choice share core numeric values
        ans_nums = extract_numbers(answer)
        choice_nums = extract_numbers(stripped)
        if ans_nums and choice_nums:
            # Exact numeric correspondence required
            if len(ans_nums) == 1 and len(choice_nums) == 1:
                if ans_nums[0] == choice_nums[0]:
                    return True

    # "15" must NOT match "5" — final safety: character count
    if norm_ans.isdigit() and not norm_stripped.isdigit():
        return False

    # Word-level containment with digit matching
    if norm_stripped.replace(",", "").replace(".", "").isdigit():
        # Only match if exact numeric equality
        try:
            if float(norm_ans) == float(norm_stripped):
                return True
        except ValueError:
            pass

    return False


def has_specific_steps(ex: dict[str, Any]) -> bool:
    """Check if steps contain specific mathematical content, not generic filler."""
    steps = ex.get("steps") or []
    expected = meta(ex).get("expected_working_steps") or []
    all_steps = list(steps) + list(expected)

    if not all_steps:
        return False

    concept_terms = re.compile(
        r"\b("
        r"median|mean|mode|range|quartile|iqr|skew|outlier|scatterplot|"
        r"correlation|association|causation|extrapolation|interpolation|"
        r"sample|bias|representative|conditional|independent|mutually exclusive|"
        r"theoretical probability|experimental probability|relative frequency|"
        r"simulation|law of large numbers|tree|branch|sample space|"
        r"gradient|intercept|vertex|parabola|linear|exponential|quadratic|"
        r"euler|circuit|degree|network|bounds?|relative error|absolute error"
        r")\b",
        re.IGNORECASE,
    )

    has_math = False
    generic_count = 0
    for step in all_steps:
        step_str = str(step)
        if re.search(r"\d|=|\\frac|\\sqrt|\^|\+|-|\*|/|%|cm|m\b|kg|\$", step_str):
            has_math = True
        elif concept_terms.search(step_str):
            has_math = True
        if GENERIC_STEP_PATTERNS.search(step_str):
            generic_count += 1

    total = len(all_steps)
    if total == 0:
        return False
    if generic_count >= total * 0.5:
        return False
    return has_math

def has_template_text(ex: dict[str, Any]) -> list[str]:
    """Detect TODO, TEMPLATE, placeholder or AI meta-text in exercise."""
    hits: list[str] = []
    content_fields = {
        "question": ex.get("question"),
        "answer": ex.get("answer"),
        "topic": ex.get("topic"),
        "id": ex.get("id"),
        "steps": ex.get("steps"),
        "sample_reasoning": ex.get("sample_reasoning"),
        "rubric": ex.get("rubric"),
        "sub_parts": ex.get("sub_parts"),
    }

    def walk(value: Any, path: str) -> None:
        if isinstance(value, str):
            if TEMPLATE_PATTERNS.search(value):
                hits.append(f"{path}: {value[:80]}")
        elif isinstance(value, list):
            for index, child in enumerate(value):
                walk(child, f"{path}[{index}]")
        elif isinstance(value, dict):
            for key, child in value.items():
                walk(child, f"{path}.{key}")

    for field, value in content_fields.items():
        walk(value, field)

    return hits


def iter_rubrics(ex: dict[str, Any]) -> Iterable[tuple[str, dict[str, Any]]]:
    """Yield top-level and part-level rubrics with a stable audit path."""
    rubric = ex.get("rubric")
    if isinstance(rubric, dict) and rubric:
        yield "rubric", rubric
    for index, part in enumerate(ex.get("sub_parts") or []):
        if not isinstance(part, dict):
            continue
        part_rubric = part.get("rubric")
        if isinstance(part_rubric, dict) and part_rubric:
            label = str(part.get("label") or index + 1)
            yield f"sub_parts[{label}].rubric", part_rubric


RUBRIC_COVERAGE_STOP_WORDS = {
    "about", "above", "answer", "both", "calculate", "each", "explain",
    "find", "given", "have", "identify", "number", "numbers", "please",
    "question", "show", "state", "such", "that", "than", "their", "then",
    "this", "using", "value", "values", "what", "which", "with", "would",
}


def _rubric_token_stem(token: str) -> str:
    """Normalise simple English inflections without attempting semantic matching."""
    if token.endswith("ility") and len(token) > 7:
        token = f"{token[:-5]}le"  # reliability -> reliable
    elif token.endswith("ies") and len(token) > 5:
        token = f"{token[:-3]}y"  # studies -> study
    elif token.endswith("ing") and len(token) > 7:
        token = token[:-3]
    elif token.endswith("ed") and len(token) > 6:
        token = token[:-2]
    elif token.endswith("es") and len(token) > 5:
        token = token[:-2]
    elif token.endswith("s") and not token.endswith("ss") and len(token) > 4:
        token = token[:-1]
    return token


def _rubric_coverage_tokens(value: Any) -> set[str]:
    """Return substantive terms for conservative rubric-to-part matching."""
    plain = re.sub(r"\\[A-Za-z]+", " ", str(value or "")).lower()
    return {
        _rubric_token_stem(token) for token in re.findall(r"[a-z]{4,}", plain)
        if token not in RUBRIC_COVERAGE_STOP_WORDS
    }


def _rubric_coverage_numbers(value: Any) -> set[str]:
    """Return non-trivial numbers; 0/1 are too common to prove coverage."""
    return {
        token for token in re.findall(r"\d+(?:\.\d+)?", str(value or ""))
        if float(token) >= 2
    }


def top_level_rubric_covers_subpart(ex: dict[str, Any], part: dict[str, Any]) -> bool:
    """Whether a concrete top-level key point can be traced to a sub-part.

    Existing banks commonly keep one item-level rubric rather than duplicating
    the same criterion below every sub-part.  We accept that layout only when a
    key point shares a non-trivial number or at least two substantive terms with
    the part's question/answer.  This prevents a generic item-level rubric from
    silently standing in for part-level marking guidance.
    """
    rubric = ex.get("rubric")
    if not isinstance(rubric, dict):
        return False
    key_points = rubric.get("key_points")
    if not isinstance(key_points, list) or not key_points:
        return False

    part_context = "\n".join(
        str(part.get(field) or "") for field in ("question", "answer", "steps")
    )
    part_terms = _rubric_coverage_tokens(part_context)
    part_numbers = _rubric_coverage_numbers(part_context)
    for key_point in key_points:
        if not isinstance(key_point, str) or not key_point.strip():
            continue
        if part_numbers & _rubric_coverage_numbers(key_point):
            return True
        if len(part_terms & _rubric_coverage_tokens(key_point)) >= 2:
            return True
    return False


def combined_text(ex: dict[str, Any]) -> str:
    """Combine all relevant text fields for analysis."""
    parts = [str(ex.get(k, "")) for k in ["question", "answer", "topic"]]
    for step in ex.get("steps") or []:
        parts.append(str(step))
    m = meta(ex)
    for k in ["strand", "sub_strand", "skill"]:
        if m.get(k):
            parts.append(str(m[k]))
    return "\n".join(parts)


def compound_short_answer_needs_review(ex: dict[str, Any]) -> bool:
    """Conservatively flag short-answer prompts that appear to require several outputs."""
    if ex.get("question_type") != "short_answer":
        return False
    question = str(ex.get("question") or "")
    answer = str(ex.get("answer") or "")
    labelled_parts = {
        m.group(1).lower()
        for m in re.finditer(r"(?:^|[\s;])\(?([a-e])\)\s*", question, re.I)
    }
    if len(labelled_parts) >= 2:
        answered = {
            m.group(1).lower()
            for m in re.finditer(r"(?:^|[\s;])\(?([a-e])\)\s*", answer, re.I)
        }
        return not labelled_parts.issubset(answered)

    commands = re.findall(
        r"\b(?:find|calculate|determine|state|rank|list|predict|describe|explain|justify|give|conclude)\b|how many",
        question,
        re.I,
    )
    return len(commands) >= 2 and words_in_text(answer) < 15


def words_in_text(value: Any) -> int:
    return len(re.findall(r"[A-Za-z0-9]+", str(value or "")))


