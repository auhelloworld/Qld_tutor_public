def load_exercises(path: Path) -> list[dict[str, Any]]:
    """Load exercises from a JSON file, handling encoding variations."""
    raw = path.read_text(encoding="utf-8")
    # Strip BOM if present
    if raw.startswith("\ufeff"):
        raw = raw[1:]
    exercises = json.loads(raw)
    return [
        ex for ex in exercises
        if isinstance(ex, dict) and ex.get("status", "active") == "active"
    ]


def _safe_rel(path: Path, root: Path) -> str:
    """Return path relative to root if possible, else the absolute path string.

    Avoids ValueError when --out points outside the project root.
    """
    try:
        return str(path.relative_to(root))
    except ValueError:
        return str(path)


def load_curriculum_topics(data_dir: Path, year: int) -> set[str]:
    """Load the set of valid topic_ids for a given curriculum year."""
    path = data_dir / "curriculum" / "ac9_maths" / f"year{year}.json"
    if not path.exists():
        return set()

    data = json.loads(path.read_text(encoding="utf-8"))
    topic_ids: set[str] = set()

    def _collect(obj: Any) -> None:
        if isinstance(obj, dict):
            tid = obj.get("topic_id")
            if tid:
                topic_ids.add(str(tid))
            for v in obj.values():
                _collect(v)
        elif isinstance(obj, list):
            for item in obj:
                _collect(item)

    _collect(data)
    return topic_ids


