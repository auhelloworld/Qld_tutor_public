def audit_schema(ex: dict[str, Any], year: int, valid_topic_ids: set[str]) -> list[IssueFlag]:
    """Run full schema and content audit on a single exercise item."""
    issues: list[IssueFlag] = []
    qid = str(ex.get("id", "unknown"))

    def add(category: str, severity: str, code: str, message: str, evidence: str = "", fix: str = "") -> None:
        issues.append(IssueFlag(
            exercise_id=qid, category=category, severity=severity,
            code=code, message=message, validator="schema",
            evidence=evidence, recommended_fix=fix,
        ))

    try:
        ExerciseItem.model_validate(ex)
    except ValidationError as exc:
        first = exc.errors(include_url=False)[0]
        location = ".".join(str(part) for part in first.get("loc", ())) or "item"
        add(
            "hard_error", "critical", "canonical_schema_validation",
            f"ExerciseItem validation failed at {location}: {first.get('msg', 'invalid value')}",
            evidence=str(exc),
            fix="Make the item conform to core.schema.exercise_schema.ExerciseItem.",
        )

    # Required fields
    for field in REQUIRED_FIELDS:
        if field not in ex:
            add("hard_error", "critical", "missing_required_field",
                f"Missing required field: {field}",
                f"Add field '{field}' to the exercise item.")
        elif ex[field] is None:
            add("hard_error", "critical", "null_required_field",
                f"Required field is null: {field}",
                f"Field '{field}' must have a non-null value.")

    # Framework
    framework = str(ex.get("framework", ""))
    if framework != "AC9_MATHS":
        add("hard_error", "critical", "invalid_framework",
            f"Framework is {framework!r}, expected 'AC9_MATHS'.",
            "Set framework to 'AC9_MATHS'.")

    # Subject
    subject = str(ex.get("subject", "")).lower()
    if subject != "math":
        add("hard_error", "critical", "invalid_subject",
            f"Subject is {subject!r}, expected 'math'.",
            "Set subject to 'math'.")

    # Year level
    item_year = ex.get("year_level")
    if item_year is not None and item_year != year:
        add("hard_error", "high", "year_level_mismatch",
            f"year_level={item_year}, expected={year}.",
            f"Move item to Year {item_year} bank or correct year_level.")

    # topic_ids
    topic_ids = ex.get("topic_ids") or []
    if not isinstance(topic_ids, list) or not topic_ids:
        add("hard_error", "high", "missing_topic_ids",
            "topic_ids is missing or empty.",
            "Add at least one AC9 mathematics topic id.")
    else:
        prefix = YEAR_PREFIX.get(year, "AC9M")
        for tid in topic_ids:
            tid_str = str(tid)
            if tid_str not in valid_topic_ids:
                add("content_error", "high", "unknown_topic_id",
                    f"topic_id {tid_str!r} not found in Year {year} curriculum.",
                    "Use a valid curriculum topic id or add exercise to correct year bank.")
            if prefix and not tid_str.startswith(prefix):
                add("content_error", "medium", "topic_prefix_mismatch",
                    f"topic_id {tid_str!r} does not match year prefix {prefix}.",
                    "Verify topic belongs to this year level.")

    # Valid question_type
    qt = str(ex.get("question_type", ""))
    if qt not in VALID_QTYPES:
        add("hard_error", "high", "invalid_question_type",
            f"Invalid question_type: {qt!r}.",
            "Use one of: short_answer, multiple_choice, reasoning, multi_part.")

    # Valid difficulty
    diff = str(ex.get("difficulty", ""))
    if diff not in VALID_DIFFICULTY:
        add("content_error", "medium", "invalid_difficulty",
            f"Invalid difficulty: {diff!r}.",
            "Use one of: foundational, developing, extending, AMC.")

    # Valid complexity
    comp = str(ex.get("complexity", ""))
    if comp not in VALID_COMPLEXITY:
        add("content_error", "medium", "invalid_complexity",
            f"Invalid complexity: {comp!r}.",
            "Use one of: simple_familiar, complex_familiar, complex_unfamiliar.")

    # math_metadata
    m = meta(ex)
    if not m:
        add("hard_error", "high", "missing_math_metadata",
            "math_metadata is missing or empty.",
            "Add strand, sub_strand, skill, and expected_working_steps.")
    else:
        for key in ["strand", "sub_strand", "skill"]:
            if not str(m.get(key, "")).strip():
                add("content_error", "medium", f"missing_metadata_{key}",
                    f"math_metadata.{key} is missing.",
                    f"Add math_metadata.{key}.")
        expected_steps = m.get("expected_working_steps")
        if not isinstance(expected_steps, list) or not expected_steps:
            if diff in {"developing", "extending", "AMC"}:
                add("content_error", "medium", "missing_expected_working_steps",
                    f"math_metadata.expected_working_steps missing for {diff} item.",
                    "Add worked mathematical steps for self-study and marking support.")
            else:
                add("advisory", "low", "missing_expected_working_steps",
                    "math_metadata.expected_working_steps missing.",
                    "Add worked mathematical steps for self-study support.")

    # Steps
    steps = ex.get("steps") or []
    if not isinstance(steps, list) or not steps:
        add("content_error", "high", "missing_steps",
            "No steps provided.",
            "Add worked steps for self-study feedback.")
    elif not has_specific_steps(ex) and qt != "multiple_choice":
        add("review_needed", "medium", "generic_steps",
            "Steps appear generic or lack mathematical working.",
            "Include concrete operations, equations, or substitutions.")

    # Reasoning-specific checks
    if qt == "reasoning":
        if not isinstance(ex.get("rubric"), dict) or not ex.get("rubric"):
            add("content_error", "high", "reasoning_missing_rubric",
                "Reasoning item missing rubric.",
                "Add key_points and max_score for AI/self-check marking.")
        if not str(ex.get("sample_reasoning", "")).strip():
            add("content_error", "high", "reasoning_missing_sample",
                "Reasoning item missing sample_reasoning.",
                "Add a model reasoning response.")

    # Multi-part checks
    if qt == "multi_part":
        sub_parts = ex.get("sub_parts") or []
        if not isinstance(sub_parts, list) or len(sub_parts) < 2:
            add("hard_error", "critical", "multi_part_missing_sub_parts",
                f"Multi-part item has {len(sub_parts) if isinstance(sub_parts, list) else 'no'} sub_parts, expected at least 2.",
                "Add at least 2 labelled sub_parts with separate questions and answers.")
        else:
            labels: list[str] = []
            for idx, part in enumerate(sub_parts):
                if not isinstance(part, dict):
                    add("hard_error", "high", "multi_part_invalid_sub_part",
                        f"Sub-part {idx + 1} is not a dictionary.",
                        "Each sub_part must be a dict with label, question, answer.")
                else:
                    label = str(part.get("label", "")).strip()
                    if not label:
                        add("content_error", "medium", "multi_part_missing_label",
                            f"Sub-part {idx + 1} missing label.",
                            f"Add a label (e.g. 'a', 'b') to sub-part {idx + 1}.")
                    else:
                        labels.append(label.lower())
                    if not str(part.get("question", "")).strip():
                        add("content_error", "high", "multi_part_missing_question",
                            f"Sub-part {idx + 1} missing question.",
                            f"Add question text to sub-part {idx + 1}.")
                    if not str(part.get("answer", "")).strip():
                        add("content_error", "high", "multi_part_missing_answer",
                            f"Sub-part {idx + 1} missing answer.",
                            f"Add answer to sub-part {idx + 1}.")
                    try:
                        part_max = float(part.get("max_score", part.get("marks", 1)) or 0)
                    except (TypeError, ValueError):
                        part_max = 0.0
                    has_part_rubric = isinstance(part.get("rubric"), dict) and bool(part.get("rubric"))
                    if part_max > 1 and not has_part_rubric and not top_level_rubric_covers_subpart(ex, part):
                        add("review_needed", "medium", "multi_part_part_rubric_missing",
                            f"Sub-part {label or idx + 1} is worth {part_max:g} marks but has no traceable rubric criterion.",
                            "Add a task-specific part rubric or a concrete top-level key point that clearly maps to this part.")
            duplicate_labels = sorted(label for label, count in Counter(labels).items() if count > 1)
            if duplicate_labels:
                add("hard_error", "high", "multi_part_duplicate_labels",
                    f"Multi-part item has duplicate labels: {duplicate_labels}.",
                    "Use a unique label for each sub-part so student answers and partial credit map safely.")
            if not isinstance(ex.get("rubric"), dict) or not ex.get("rubric"):
                add("review_needed", "medium", "multi_part_missing_rubric",
                    "Multi-part item without rubric.",
                    "Add rubric for multi-part scoring.")
            if not str(ex.get("sample_reasoning", "")).strip():
                add("review_needed", "medium", "multi_part_missing_sample_reasoning",
                    "Multi-part item without sample_reasoning.",
                    "Add a model reasoning response for self-study support.")

    # MCQ checks
    if qt == "multiple_choice":
        choices = ex.get("choices") or []
        correct_choice = str(ex.get("correct_choice", "")).strip().upper()
        if not isinstance(choices, list) or len(choices) < 2:
            add("hard_error", "critical", "mcq_too_few_choices",
                f"MCQ has {len(choices) if isinstance(choices, list) else 'no'} choices, expected at least 2.",
                "Add at least 2 non-empty choices.")
        key_index = (
            ord(correct_choice) - ord("A")
            if correct_choice in VALID_CHOICES
            else -1
        )
        if key_index < 0 or not isinstance(choices, list) or key_index >= len(choices):
            add("hard_error", "critical", "mcq_invalid_correct_choice",
                f"correct_choice={correct_choice!r} is not a valid key for {len(choices) if isinstance(choices, list) else 0} choices.",
                "Set correct_choice to a letter whose index exists in the choice list.")
        if isinstance(choices, list):
            choice_texts = [re.sub(r"^[A-Z]\s*[\).:-]\s*", "", str(c), flags=re.I).strip() for c in choices]
            if len(choice_texts) != len(set(choice_texts)):
                add("hard_error", "high", "mcq_duplicate_choices",
                    "Duplicate choices in MCQ.",
                    "Make all distractors distinct.")
        if (
            isinstance(choices, list)
            and choices
            and key_index >= 0
            and key_index < len(choices)
            and not mcq_answer_matches_choice(ex)
        ):
            add("content_error", "high", "mcq_answer_choice_mismatch",
                "MCQ answer does not match correct_choice text.",
                "Ensure answer field matches the text of the correct choice or is the choice letter.",
                fix="Align answer with correct_choice after normalisation.")
    if compound_short_answer_needs_review(ex):
        add(
            "review_needed", "medium", "compound_short_answer_may_be_incomplete",
            "Short-answer prompt appears to request multiple outputs, but the answer may not address each one.",
            "Check every requested calculation, conclusion, explanation, prediction, or labelled part.",
        )
    # Generic rubric check: reasoning/multi-part rubrics that only contain
    # generic phrases (e.g. "key points", "marks") provide no real marking
    # guidance for AI/self-check. Detect shallow rubric structures.
    for rubric_path, rubric in iter_rubrics(ex):
        rubric_blob = json.dumps(rubric, ensure_ascii=False).lower()
        # A rubric with only generic keys and short values is likely shallow.
        generic_rubric_phrases = [
            "key points", "max score", "total marks", "marking guide",
            "see rubric", "as above", "n/a",
        ]
        values_text = " ".join(str(v) for v in rubric.values()).strip()
        if len(rubric) <= 2 and (
            len(values_text) < 30 or any(p in rubric_blob for p in generic_rubric_phrases)
        ):
            add("review_needed", "medium", "generic_rubric",
                f"Rubric at {rubric_path} appears generic/shallow; lacks concrete marking criteria.",
                "Add specific key_points, acceptable answers, or mark allocation per criterion.",
                fix="Populate rubric with concrete criteria and model answer elements.")

    # Template/placeholder detection
    template_hits = has_template_text(ex)
    for hit in template_hits:
        add("content_error", "high", "template_text",
            f"Template/placeholder text found: {hit}",
            "Replace with actual content.",
            fix="Complete or replace template/placeholder content.")

    # Difficulty/complexity miscalibration
    if diff == "foundational" and comp == "complex_unfamiliar":
        add("review_needed", "low", "difficulty_complexity_mismatch",
            "Foundational item with complexity='complex_unfamiliar' seems miscalibrated.",
            "Review difficulty/complexity calibration.")
    if diff in {"extending", "AMC"} and comp == "simple_familiar":
        add("review_needed", "low", "difficulty_complexity_mismatch",
            f"{diff} item with complexity='simple_familiar' seems miscalibrated.",
            "Review difficulty/complexity calibration.")

    return issues


