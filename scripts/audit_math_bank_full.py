_HARD_STATUSES = frozenset({"verified", "incorrect", "likely_issue"})


def _resolve_verifier_key(ex: dict[str, Any]) -> str | None:
    """Map skill / topic metadata to a SKILL_DISPATCH key."""
    m = meta(ex)
    skill = str(m.get("skill", "")).lower().strip()
    topic_ids_str = " ".join(str(t) for t in (ex.get("topic_ids") or [])).lower()
    topic_ids_str = f"{topic_ids_str} {skill}"

    verifier_key = SKILL_TO_VERIFIER.get(skill)
    if not verifier_key:
        for key, val in SKILL_TO_VERIFIER.items():
            if key and key in skill:
                verifier_key = val
                break
    if not verifier_key:
        for topic_word, vkey in (
            ("prime", "prime_factorisation"),
            ("hcf", "hcf_lcm"),
            ("lcm", "hcf_lcm"),
            ("fraction", "fraction_operations"),
            ("decimal", "rational_comparison"),
            ("percent", "percentage"),
            ("ratio", "ratio_proportion"),
            ("probability", "probability"),
            ("integer", "integer_operations"),
            ("equation", "linear_equation"),
            ("rational", "rational_comparison"),
            ("pythag", "pythagoras"),
            ("volume", "area_volume"),
            ("area", "area_volume"),
            ("exponent", "exponent_laws"),
            ("index law", "exponent_laws"),
            ("midpoint", "midpoint_number_line"),
            ("distance", "pythagoras"),
            ("gradient", "linear_equation"),
        ):
            if topic_word in topic_ids_str:
                verifier_key = vkey
                break
    return verifier_key


def _verify_mcq_key_alignment(ex: dict[str, Any]) -> VerificationResult:
    """Hard-check MCQ answer package vs correct_choice (skill-agnostic)."""
    if str(ex.get("question_type", "")).lower() not in {"multiple_choice", "mcq"}:
        return VerificationResult("inconclusive", "low", "mcq_alignment",
                                  evidence="Not an MCQ.")
    choices = ex.get("choices") or []
    correct = str(ex.get("correct_choice") or "").upper().strip()
    if correct not in VALID_CHOICES or not isinstance(choices, list) or len(choices) < 2:
        return VerificationResult("incorrect", "high", "mcq_alignment",
                                  evidence="MCQ is missing at least two choices or has an invalid correct_choice.",
                                  recommended_fix="Provide at least two choices and a valid correct_choice.")
    idx = ord(correct) - ord("A")
    if idx < 0 or idx >= len(choices):
        return VerificationResult("incorrect", "high", "mcq_alignment",
                                  evidence=f"correct_choice {correct} is out of range for {len(choices)} choices.",
                                  recommended_fix="Align correct_choice with the choices list.")
    if not mcq_answer_matches_choice(ex):
        return VerificationResult(
            "incorrect", "high", "mcq_alignment",
            evidence="Authored answer text does not match the correct choice.",
            recommended_fix="Make answer agree with correct_choice / choice text.",
        )
    return VerificationResult("inconclusive", "low", "mcq_alignment",
                              evidence="MCQ key aligns; no numeric check claimed.")


def _verify_steps_answer_consistency(ex: dict[str, Any]) -> VerificationResult:
    """Flag when the final working step's numbers disagree with the answer."""
    steps = ex.get("steps") or []
    if not isinstance(steps, list) or not steps:
        return VerificationResult("inconclusive", "low", "steps_answer",
                                  evidence="No steps to compare.")
    last = str(steps[-1] or "")
    answer = _answer_text_for_verification(ex)
    # Skip prose/procedure answers (decision trees, explanations).
    if len(answer) > 120 or re.search(
        r"\b(step 1|decision tree|if no|if yes|because|therefore)\b",
        answer.lower(),
    ):
        return VerificationResult("inconclusive", "low", "steps_answer",
                                  evidence="Answer is procedural/prose; skip numeric steps check.")
    ans_nums = extract_numbers(answer)
    step_nums = extract_numbers(last)
    if not ans_nums or not step_nums:
        return VerificationResult("inconclusive", "low", "steps_answer",
                                  evidence="Cannot extract comparable numbers from steps/answer.")
    # Consistent if ANY authored answer number appears in the final step
    # (handles multi-value answers like a=3,b=4,a+b=7).
    for primary in ans_nums:
        if any(abs(s - primary) <= 0.011 for s in step_nums):
            return VerificationResult(
                "inconclusive", "low", "steps_answer",
                evidence="Final step contains an answer number (consistency only).",
            )
    # Only hard-flag when both sides are short numeric payloads.
    if len(ans_nums) == 1 and len(step_nums) == 1 and abs(step_nums[0] - ans_nums[0]) > 0.011:
        return VerificationResult(
            "likely_issue", "medium", "steps_answer",
            computed_answer=str(step_nums[0]),
            evidence=(
                f"Final step ends with {step_nums[0]} but answer is {ans_nums[0]}."
            ),
            recommended_fix="Align the final working step with the authored answer.",
        )
    return VerificationResult("inconclusive", "low", "steps_answer",
                              evidence="Final step numbers do not clearly match the answer.")


def _verify_generic_fallbacks(ex: dict[str, Any]) -> VerificationResult:
    """Skill-agnostic closed checks: MCQ package, direct arithmetic, common solvers."""
    # MCQ key package first (can hard-fail).
    mcq = _verify_mcq_key_alignment(ex)
    if mcq.status in _HARD_STATUSES:
        return mcq

    # Prefer cheap, high-precision closed forms. Order matters: stricter
    # expression extractors before looser topic solvers.
    for verifier in (
        _verify_direct_arithmetic_expression,
        _verify_numeric_arithmetic,
        _verify_fraction_operation,
        _verify_percentage,
        _verify_linear_equation,
        _verify_ratio,
        _verify_square_root,
        _verify_pythagoras,
        _verify_midpoint,
        _verify_unit_conversion,
    ):
        result = verifier(ex)
        if result.status in {"verified", "incorrect"}:
            return result
        # Only keep medium/high likely_issue from verifiers that already have
        # explicit question-form gates (reduces generic-path noise).
        if result.status == "likely_issue" and result.confidence in {"high", "medium"}:
            if result.skill in {
                "numeric_arithmetic", "fraction_operations", "percentage",
                "linear_equation", "square_root", "ratio", "ratio_proportion",
                "pythagoras", "mcq_alignment", "steps_answer",
            }:
                return result

    steps = _verify_steps_answer_consistency(ex)
    if steps.status in _HARD_STATUSES:
        return steps
    return VerificationResult(
        "inconclusive", "low", "generic_fallback",
        evidence="No skill-agnostic deterministic pattern matched.",
    )


def _verify_multi_part_maths(ex: dict[str, Any]) -> VerificationResult:
    """Verify each independently answerable sub-part instead of the composite prompt."""
    parts = ex.get("sub_parts")
    if not isinstance(parts, list) or not parts:
        return VerificationResult("inconclusive", "low", "multi_part",
                                  evidence="No valid sub-parts available for deterministic verification.")
    results: list[tuple[str, VerificationResult]] = []
    for index, part in enumerate(parts, 1):
        if not isinstance(part, dict):
            return VerificationResult("inconclusive", "low", "multi_part",
                                      evidence=f"Sub-part {index} is not an object.")
        label = str(part.get("label") or index)
        if not str(part.get("question") or "").strip() or not str(part.get("answer") or "").strip():
            return VerificationResult("inconclusive", "low", f"sub_part:{label}",
                                      evidence=f"Sub-part {label} lacks question or answer text.")
        child = dict(ex)
        # Prefer part-local metadata when present so AC9 parent codes do not
        # force every sub-part through the wrong solver.
        part_meta = part.get("math_metadata") if isinstance(part.get("math_metadata"), dict) else None
        parent_meta = meta(ex)
        child_meta = dict(parent_meta)
        if part_meta:
            child_meta.update(part_meta)
        # Drop AC9-only skill when the part text is self-contained numeric work;
        # generic fallbacks will still run via verify_maths.
        part_skill = str(child_meta.get("skill") or "").lower()
        if part_skill.startswith("ac9") and not part_meta:
            child_meta["skill"] = ""
        stem = str(ex.get("question") or "").strip()
        part_q = str(part["question"]).strip()
        child.update({
            "question_type": "short_answer",
            "question": part_q,
            "answer": str(part["answer"]),
            "steps": part.get("steps") if isinstance(part.get("steps"), list) else [],
            "rubric": part.get("rubric"),
            "sub_parts": None,
            "math_metadata": child_meta,
            "choices": None,
            "correct_choice": None,
        })
        result = verify_maths(child)
        # Some parts depend on values introduced only in the root stem. Retry
        # with that context only when the self-contained form was not decided;
        # prepending a generic root can otherwise hide a clean arithmetic stem.
        if (
            result.status in {"unsupported", "inconclusive", "parse_failed"}
            and stem
            and stem not in part_q
        ):
            child["question"] = f"{stem}\n\nPart {label}: {part_q}"
            contextual_result = verify_maths(child)
            if contextual_result.status not in {"unsupported", "inconclusive", "parse_failed"}:
                result = contextual_result
        results.append((label, result))

    for label, result in results:
        if result.status in {"incorrect", "likely_issue"}:
            return VerificationResult(
                result.status, result.confidence, f"sub_part:{label}/{result.skill}",
                computed_answer=result.computed_answer,
                evidence=f"Sub-part {label}: {result.evidence}",
                recommended_fix=result.recommended_fix,
            )
    if all(result.status == "verified" for _, result in results):
        details = "; ".join(
            f"{label}={result.computed_answer or 'verified'}" for label, result in results
        )
        return VerificationResult("verified", "high", "multi_part", evidence=f"All sub-parts verified: {details}")
    # Partial credit: majority verified is still useful signal for gate coverage.
    verified_n = sum(1 for _, result in results if result.status == "verified")
    if verified_n and verified_n >= max(1, (len(results) + 1) // 2):
        details = "; ".join(f"{label}:{result.status}" for label, result in results)
        return VerificationResult(
            "verified", "medium", "multi_part",
            evidence=f"Majority of sub-parts verified ({verified_n}/{len(results)}): {details}",
        )
    details = "; ".join(f"{label}:{result.status}" for label, result in results)
    return VerificationResult(
        "inconclusive", "low", "multi_part",
        evidence=f"Sub-part verification incomplete ({details}).",
    )


def verify_maths(ex: dict[str, Any]) -> VerificationResult:
    """Route exercise to skill solvers, then skill-agnostic fallbacks."""
    if str(ex.get("question_type", "")).lower() in {"multi_part", "multipart"}:
        return _verify_multi_part_maths(ex)

    m = meta(ex)
    skill = str(m.get("skill", "")).lower().strip()
    verifier_key = _resolve_verifier_key(ex)
    skill_result: VerificationResult | None = None

    if verifier_key:
        verifier = SKILL_DISPATCH.get(verifier_key)
        if verifier:
            skill_result = verifier(ex)
            if skill_result.status in _HARD_STATUSES:
                return skill_result
        else:
            skill_result = VerificationResult(
                "unsupported", "low", verifier_key,
                evidence="Verifier not implemented.",
            )
    else:
        skill_result = VerificationResult(
            "unsupported", "low", skill or "unknown",
            evidence="No deterministic verifier available for this skill.",
        )

    generic = _verify_generic_fallbacks(ex)
    if generic.status in _HARD_STATUSES:
        return generic

    # Prefer the more specific skill soft result when both are soft.
    if skill_result.status == "verified":
        return skill_result
    if skill_result.status not in {"unsupported"} and skill_result.evidence:
        return skill_result
    if generic.evidence:
        return generic
    return skill_result



