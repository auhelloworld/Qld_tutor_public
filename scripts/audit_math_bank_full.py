def audit_year(year: int, data_dir: Path, out_dir: Path) -> dict[str, Any]:
    """Run full audit on a single year's exercise bank."""
    data_file = data_dir / f"exercise_{year}_math.json"
    if not data_file.exists():
        print(f"ERROR: Data file not found: {data_file}")
        sys.exit(1)

    exercises = load_exercises(data_file)
    valid_topic_ids = load_curriculum_topics(data_dir, year)
    prefix = f"year{year}_math"

    # Ensure output directory
    out_dir.mkdir(parents=True, exist_ok=True)

    all_issues: list[IssueFlag] = []
    all_rows: list[AuditRow] = []
    ids = Counter(str(ex.get("id", "")) for ex in exercises)

    # Report missing curriculum file as a hard error (avoids false "unknown topic_id"
    # cascades when the curriculum source is absent rather than the exercise being wrong).
    curriculum_path = data_dir / "curriculum" / "ac9_maths" / f"year{year}.json"
    if not curriculum_path.exists():
        all_issues.append(IssueFlag(
            exercise_id="*bank-level*",
            category="hard_error", severity="critical",
            code="curriculum_file_missing",
            message=f"Curriculum file not found: {curriculum_path}",
            validator="schema",
            evidence="Without the curriculum file, topic_id validation cannot run reliably.",
            recommended_fix=f"Add {curriculum_path} or correct the --data-dir.",
        ))

    # Duplicate id check: emit a hard_error/critical IssueFlag for each repeated id.
    duplicate_ids: list[str] = []
    for dup_qid, count in ids.items():
        if dup_qid and count > 1:
            duplicate_ids.append(dup_qid)
            all_issues.append(IssueFlag(
                exercise_id=dup_qid,
                category="hard_error", severity="critical",
                code="duplicate_id",
                message=f"Duplicate exercise id appears {count} times.",
                validator="schema",
                recommended_fix="Make every exercise id unique.",
            ))

    # Duplicate question text is only an exact duplicate when the full content
    # payload also matches. Parameterised/represented variants stay in the
    # review queue with a lower-severity, explicit variant code.
    questions_by_text: dict[str, list[dict[str, Any]]] = {}
    for ex in exercises:
        question_key = _duplicate_question_key(ex.get("question", ""))
        if question_key:
            questions_by_text.setdefault(question_key, []).append(ex)
    duplicate_questions: list[str] = []
    duplicate_question_variants: list[str] = []
    for q_text, group in questions_by_text.items():
        if len(group) <= 1:
            continue
        fingerprints = {_duplicate_fingerprint(ex) for ex in group}
        if len(fingerprints) == 1:
            duplicate_questions.append(q_text)
            all_issues.append(IssueFlag(
                exercise_id="*bank-level*",
                category="review_needed", severity="high",
                code="duplicate_question",
                message=f"Exact question payload appears {len(group)} times: {q_text[:80]!r}",
                validator="schema",
                evidence=f"Count: {len(group)}; content fingerprint is identical.",
                recommended_fix="Review duplicates; remove redundant copies or retain one canonical item.",
            ))
        else:
            duplicate_question_variants.append(q_text)
            all_issues.append(IssueFlag(
                exercise_id="*bank-level*",
                category="review_needed", severity="medium",
                code="duplicate_question_variant",
                message=f"Question stem has {len(group)} content variants: {q_text[:80]!r}",
                validator="schema",
                evidence=f"Count: {len(group)}; distinct content fingerprints: {len(fingerprints)}.",
                recommended_fix="Review parameterised variants for useful diversity before consolidating.",
            ))

    # Counters for statistics
    qtype_counts: Counter[str] = Counter()
    difficulty_counts: Counter[str] = Counter()
    complexity_counts: Counter[str] = Counter()
    strand_counts: Counter[str] = Counter()
    topic_set: set[str] = set()
    diagram_type_counts: Counter[str] = Counter()
    diagram_count = 0
    hard_issues: Counter[str] = Counter()  # severity counts
    content_error_count = 0
    review_needed_count = 0
    advisory_count = 0
    schema_issues = 0
    maths_issues = 0
    diagram_issues = 0
    extension_issues = 0
    maths_status_counts: Counter[str] = Counter()
    ext_classification_counts: Counter[str] = Counter()
    ext_evaluated = 0
    amc_flags_total = 0

    for ex in exercises:
        qid = str(ex.get("id", "unknown"))
        m = meta(ex)
        qt = str(ex.get("question_type", ""))
        diff = str(ex.get("difficulty", ""))
        comp = str(ex.get("complexity", ""))
        strand = str(m.get("strand", ""))

        # Update distribution counters
        qtype_counts[qt] += 1
        difficulty_counts[diff] += 1
        complexity_counts[comp] += 1
        strand_counts[strand or "missing"] += 1
        for tid in ex.get("topic_ids") or []:
            topic_set.add(str(tid))

        # Validator 1: Schema audit
        schema_issues_list = audit_schema(ex, year, valid_topic_ids)
        schema_issues += len(schema_issues_list)

        # Validator 2: Maths verification
        maths_result = verify_maths(ex)
        maths_issues_list: list[IssueFlag] = []
        # Soften residual low-confidence likely issues before export/stats.
        if maths_result.status == "likely_issue" and maths_result.confidence == "low":
            maths_result = VerificationResult(
                "inconclusive",
                "low",
                maths_result.skill,
                evidence=maths_result.evidence,
            )
        if maths_result.status in {"incorrect", "likely_issue"}:
            maths_issues += 1
            # Only high-confidence, pattern-specific solvers may emit content_error.
            HIGH_CONFIDENCE_SKILLS = {
                "square_root", "fraction_operations", "prime_factorisation",
                "mean_median_mode_range", "place_value_constraints",
                "numeric_arithmetic", "mcq_alignment", "percentage",
                # hcf_lcm stays review-only: factor-form inputs false-positive often.
            }
            skill_name = str(maths_result.skill or "")
            skill_leaf = skill_name.split("/")[-1] if skill_name else ""
            is_high_confidence = (
                skill_leaf in HIGH_CONFIDENCE_SKILLS
                or skill_name in HIGH_CONFIDENCE_SKILLS
            ) and maths_result.confidence in {"high", "medium"}
            if maths_result.status == "incorrect":
                if is_high_confidence:
                    category, severity = "content_error", "high"
                    label = "incorrect"
                else:
                    category, severity = "review_needed", "high"
                    label = "possible maths issue — requires review"
            else:  # likely_issue
                category, severity = "review_needed", "medium"
                label = "possible maths issue"
            maths_issues_list.append(IssueFlag(
                exercise_id=qid, category=category, severity=severity,
                code=f"maths_{maths_result.status}",
                message=(
                    f"Maths verification: {label} "
                    f"(skill={maths_result.skill}). {maths_result.evidence}"
                ),
                validator="maths",
                evidence=maths_result.evidence,
                recommended_fix=maths_result.recommended_fix,
                confidence=maths_result.confidence,
            ))
        elif maths_result.status == "parse_failed":
            maths_issues_list.append(IssueFlag(
                exercise_id=qid, category="review_needed", severity="low",
                code="maths_parse_failed",
                message=f"Maths verification: could not parse answer (skill={maths_result.skill}). {maths_result.evidence}",
                validator="maths",
                evidence=maths_result.evidence,
                recommended_fix="Review answer format for deterministic verification.",
                confidence="low",
            ))
        maths_status_counts[maths_result.status] += 1

        # Validator 3: Diagram verification
        diagram_issues_list = verify_diagram(ex)
        diagram_issues += len(diagram_issues_list)
        diagram_data = ex.get("diagram_data")
        if isinstance(diagram_data, dict) and diagram_data.get("type"):
            diagram_count += 1
            diagram_type_counts[str(diagram_data["type"])] += 1

        # Validator 4: Extension/AMC quality
        ext_result = evaluate_extension_quality(ex)
        if ext_result["classification"] != "not_applicable":
            ext_evaluated += 1
            ext_classification_counts[ext_result["classification"]] += 1
            amc_flags_total += len(ext_result.get("amc_flags", []))
            if ext_result["classification"] == "routine_mislabeled":
                # Heuristic classification — route to review queue rather than
                # hard content_error so it doesn't fail --strict on judgement calls.
                schema_issues_list.append(IssueFlag(
                    exercise_id=qid, category="review_needed", severity="high",
                    code="extension_routine_mislabeled",
                    message=f"Extension/AMC item classified as routine (score={ext_result['score']}).",
                    validator="extension",
                    evidence=f"Dimensions: {ext_result['dimensions']}",
                    recommended_fix="Increase multi-step reasoning, non-routine strategy, or unfamiliar transfer demand.",
                ))
                extension_issues += 1
            elif ext_result["classification"] == "weak_extension":
                schema_issues_list.append(IssueFlag(
                    exercise_id=qid, category="review_needed", severity="medium",
                    code="extension_weak",
                    message=f"Weak extension/AMC item (score={ext_result['score']}).",
                    validator="extension",
                    evidence=f"Dimensions: {ext_result['dimensions']}",
                    recommended_fix="Add non-routine strategy, justification, or unfamiliar context.",
                ))
                extension_issues += 1

            if ext_result["amc_flags"]:
                for flag in ext_result["amc_flags"]:
                    if flag == "senior_content_beyond_year_level":
                        category, sev = "content_error", "high"
                    else:
                        # Heuristic AMC quality flags route to review queue.
                        category, sev = "review_needed", "medium"
                    schema_issues_list.append(IssueFlag(
                        exercise_id=qid, category=category, severity=sev,
                        code=f"amc_{flag}",
                        message=f"AMC quality flag: {flag}",
                        validator="extension",
                        evidence=f"Score={ext_result['score']}, classification={ext_result['classification']}",
                    ))
                    extension_issues += 1

        # Merge all issues
        all_issues.extend(schema_issues_list)
        all_issues.extend(maths_issues_list)
        all_issues.extend(diagram_issues_list)

        # Tally issue categories
        for issue in schema_issues_list + maths_issues_list + diagram_issues_list:
            if issue.category == "hard_error":
                hard_issues[issue.severity] += 1
            elif issue.category == "content_error":
                content_error_count += 1
            elif issue.category == "review_needed":
                review_needed_count += 1
            elif issue.category == "advisory":
                advisory_count += 1

        # Build audit row
        row = AuditRow(
            id=qid,
            topic_id=str((ex.get("topic_ids") or [None])[0]) if ex.get("topic_ids") else "",
            question_type=qt,
            difficulty=diff,
            complexity=comp,
            strand=strand,
            sub_strand=str(m.get("sub_strand", "")),
            skill=str(m.get("skill", "")),
            maths_verification=maths_result.status,
            maths_confidence=maths_result.confidence,
            diagram_status=str(ex.get("diagram_data", {}).get("type", "")) if isinstance(ex.get("diagram_data"), dict) else "",
            extension_score=str(ext_result["score"]),
            extension_classification=ext_result["classification"],
            hard_errors_count=sum(1 for i in schema_issues_list + maths_issues_list + diagram_issues_list if i.category == "hard_error"),
            content_errors_count=sum(1 for i in schema_issues_list + maths_issues_list + diagram_issues_list if i.category == "content_error"),
            review_needed_count=sum(1 for i in schema_issues_list + maths_issues_list + diagram_issues_list if i.category == "review_needed"),
            advisory_count=sum(1 for i in schema_issues_list + maths_issues_list + diagram_issues_list if i.category == "advisory"),
        )
        all_rows.append(row)

    # Deduplicate IDs (duplicate_ids/duplicate_questions already emitted as issues above)
    duplicate_ids = sorted(duplicate_ids)

    # ------------------------------------------------------------------
    # Bank-level checks: difficulty ladder completeness and topic coverage.
    # These are review_needed issues (not hard errors) — they signal gaps in
    # bank composition that need human attention but don't break individual items.
    # ------------------------------------------------------------------
    # Difficulty ladder: a balanced bank should cover foundational, developing,
    # and extending. Flag if any rung is missing or severely under-represented.
    expected_difficulties = {"foundational", "developing", "extending"}
    present_difficulties = set(difficulty_counts.keys())
    missing_difficulties = expected_difficulties - present_difficulties
    for missing_diff in sorted(missing_difficulties):
        all_issues.append(IssueFlag(
            exercise_id="*bank-level*",
            category="review_needed", severity="medium",
            code="difficulty_ladder_gap",
            message=f"Difficulty ladder incomplete: no '{missing_diff}' items in the bank.",
            validator="schema",
            evidence=f"Difficulty counts: {dict(difficulty_counts)}",
            recommended_fix=f"Add '{missing_diff}' items to complete the difficulty ladder.",
        ))
    # Flag severely under-represented rungs (< 5% of bank, only if bank is non-trivial).
    if len(exercises) >= 20:
        for diff in sorted(expected_difficulties & present_difficulties):
            frac = difficulty_counts.get(diff, 0) / len(exercises)
            if frac < 0.05:
                all_issues.append(IssueFlag(
                    exercise_id="*bank-level*",
                    category="review_needed", severity="low",
                    code="difficulty_ladder_thin",
                    message=f"Difficulty rung '{diff}' is under-represented ({difficulty_counts[diff]}/{len(exercises)} = {frac:.0%}).",
                    validator="schema",
                    evidence=f"Difficulty counts: {dict(difficulty_counts)}",
                    recommended_fix=f"Add more '{diff}' items to balance the ladder.",
                ))

    # Topic coverage: every curriculum topic_id should have at least one item.
    # Only check when the curriculum file was actually loaded.
    if valid_topic_ids:
        uncovered = valid_topic_ids - topic_set
        for tid in sorted(uncovered):
            all_issues.append(IssueFlag(
                exercise_id="*bank-level*",
                category="review_needed", severity="medium",
                code="topic_coverage_gap",
                message=f"Curriculum topic {tid} has no exercises in the bank.",
                validator="schema",
                evidence=f"Topics covered: {len(topic_set)}/{len(valid_topic_ids)}",
                recommended_fix=f"Add at least one exercise for topic {tid}.",
            ))

    # ------------------------------------------------------------------
    # Recompute issue counts from all_issues so bank-level issues (duplicate_id,
    # duplicate_question, curriculum_file_missing, difficulty/topic gaps) are
    # reflected in stats, summary, hard_errors.csv, and --strict exit code.
    # ------------------------------------------------------------------
    hard_issues_recomputed: Counter[str] = Counter()
    content_error_count = 0
    review_needed_count = 0
    advisory_count = 0
    for issue in all_issues:
        if issue.category == "hard_error":
            hard_issues_recomputed[issue.severity] += 1
        elif issue.category == "content_error":
            content_error_count += 1
        elif issue.category == "review_needed":
            review_needed_count += 1
        elif issue.category == "advisory":
            advisory_count += 1
    hard_issues = hard_issues_recomputed  # used by stats dict below

    # Write output files
    summary_path = out_dir / f"{prefix}_full_summary.md"
    item_audit_path = out_dir / f"{prefix}_item_audit.csv"
    issue_flags_path = out_dir / f"{prefix}_issue_flags.jsonl"
    maths_gate_issue_csv_path = out_dir / f"{prefix}_maths_gate_issue_flags.csv"
    hard_errors_path = out_dir / f"{prefix}_hard_errors.csv"
    human_review_path = out_dir / f"{prefix}_human_review_queue.csv"
    maths_review_path = out_dir / f"{prefix}_maths_review_queue.csv"

    stats = {
        "year": year,
        "total_items": len(exercises),
        "unique_ids": len(ids),
        "duplicate_ids": duplicate_ids,
        "duplicate_questions": len(duplicate_questions),
        "duplicate_question_variants": len(duplicate_question_variants),
        "qtype_counts": qtype_counts,
        "difficulty_counts": difficulty_counts,
        "complexity_counts": complexity_counts,
        "strand_counts": strand_counts,
        "topics_covered": len(topic_set),
        "total_issues": len(all_issues),
        "hard_errors_count": sum(hard_issues.values()),
        "hard_critical": hard_issues.get("critical", 0),
        "hard_high": hard_issues.get("high", 0),
        "hard_medium": hard_issues.get("medium", 0),
        "hard_low": hard_issues.get("low", 0),
        "content_errors_count": content_error_count,
        "review_needed_count": review_needed_count,
        "advisory_count": advisory_count,
        "schema_issues": schema_issues,
        "maths_issues": maths_issues,
        "diagram_issues": diagram_issues,
        "extension_issues": extension_issues,
        "maths_verified": maths_status_counts.get("verified", 0),
        "maths_incorrect": maths_status_counts.get("incorrect", 0),
        "maths_likely_issue": maths_status_counts.get("likely_issue", 0),
        "maths_inconclusive": maths_status_counts.get("inconclusive", 0),
        "maths_unsupported": maths_status_counts.get("unsupported", 0),
        "maths_parse_failed": maths_status_counts.get("parse_failed", 0),
        "maths_unverified": (
            maths_status_counts.get("inconclusive", 0)
            + maths_status_counts.get("unsupported", 0)
            + maths_status_counts.get("parse_failed", 0)
        ),
        "ext_evaluated": ext_evaluated,
        "ext_routine": ext_classification_counts.get("routine_mislabeled", 0),
        "ext_weak": ext_classification_counts.get("weak_extension", 0),
        "ext_adequate": ext_classification_counts.get("adequate_extension", 0),
        "ext_strong": ext_classification_counts.get("strong_extension", 0),
        "amc_flags_count": amc_flags_total,
        "diagram_count": diagram_count,
        "diagram_types": diagram_type_counts,
        "diagram_hard_errors": sum(1 for i in all_issues if i.validator == "diagram" and i.category == "hard_error"),
        "outputs": {
            "summary": _safe_rel(summary_path, ROOT),
            "item_audit": _safe_rel(item_audit_path, ROOT),
            "issue_flags": _safe_rel(issue_flags_path, ROOT),
            "maths_gate_issue_flags": _safe_rel(maths_gate_issue_csv_path, ROOT),
            "hard_errors": _safe_rel(hard_errors_path, ROOT),
            "human_review": _safe_rel(human_review_path, ROOT),
            "maths_review": _safe_rel(maths_review_path, ROOT),
        },
    }

    write_full_summary(stats, summary_path)
    write_item_audit(all_rows, item_audit_path)
    write_issue_flags(all_issues, issue_flags_path)
    write_maths_gate_issue_csv(all_issues, maths_gate_issue_csv_path)
    write_hard_errors(all_issues, hard_errors_path)
    write_human_review_queue(all_issues, human_review_path)
    write_maths_review_queue(all_rows, maths_review_path)

    return stats


