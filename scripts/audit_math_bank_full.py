def _verify_place_value_constraints(ex: dict[str, Any]) -> VerificationResult:
    """Verify conservative digit/place-value optimisation problems by enumeration."""
    question = str(ex.get("question") or "")
    normal = question.replace("\\times", "*").replace("×", "*").replace("$", "")
    terms = re.findall(r"\b([a-z])\s*\*\s*10\s*\^\s*\{?(\d+)\}?", normal, re.I)
    terms.extend((var, "1") for var in re.findall(r"\b([a-z])\s*\*\s*10(?!\s*\^)", normal, re.I))
    if re.search(r"\bfive[- ]digit number\b", normal, re.I):
        used = {var.lower() for var, _ in terms}
        for var in re.findall(r"\+\s*([a-z])\b", normal, re.I):
            if var.lower() not in used:
                terms.append((var, "0"))
                used.add(var.lower())
    if len(terms) < 2 or not re.search(r"\b(?:largest|smallest|maximum|minimum)\b", normal, re.I):
        return VerificationResult("inconclusive", "low", "place_value_constraints")

    variables = list(dict.fromkeys(var.lower() for var, _ in terms))
    exponents = {var.lower(): int(exp) for var, exp in terms}
    if len(variables) > 6 or len(exponents) != len(variables):
        return VerificationResult("inconclusive", "low", "place_value_constraints")

    nonzero = bool(re.search(r"all digits (?:are )?non[- ]zero", normal, re.I))
    digit_range = range(1, 10) if nonzero else range(10)
    equalities = re.findall(r"\b([a-z])\s*=\s*([a-z]|\d)\b", normal, re.I)
    chains = re.findall(r"\b([a-z])\s*>\s*([a-z])\s*>\s*([a-z])\b", normal, re.I)
    sum_match = re.search(
        r"\b([a-z](?:\s*\+\s*[a-z])+)\s*=\s*(\d+)\b", normal, re.I
    )
    divisible = re.search(r"divisible by\s*(\d+)", normal, re.I)
    leading = max(exponents, key=exponents.get)
    candidates: list[int] = []

    for digits in itertools.product(digit_range, repeat=len(variables)):
        values = dict(zip(variables, digits))
        if values[leading] == 0:
            continue
        if any(
            values[left.lower()] != (
                values[right.lower()] if right.isalpha() else int(right)
            )
            for left, right in equalities
            if left.lower() in values and (not right.isalpha() or right.lower() in values)
        ):
            continue
        if any(not (values[a.lower()] > values[b.lower()] > values[c.lower()]) for a, b, c in chains):
            continue
        if sum_match:
            sum_vars = re.findall(r"[a-z]", sum_match.group(1).lower())
            if not all(var in values for var in sum_vars):
                return VerificationResult("inconclusive", "low", "place_value_constraints")
            if sum(values[var] for var in sum_vars) != int(sum_match.group(2)):
                continue
        number = sum(values[var] * (10 ** exp) for var, exp in exponents.items())
        if divisible and number % int(divisible.group(1)) != 0:
            continue
        candidates.append(number)

    if not candidates:
        return VerificationResult("inconclusive", "low", "place_value_constraints")
    expected = min(candidates) if re.search(r"\b(?:smallest|minimum)\b", normal, re.I) else max(candidates)
    if _answer_matches_number(ex, float(expected), tol=0):
        return VerificationResult(
            "verified", "high", "place_value_constraints",
            computed_answer=str(expected), evidence=f"Enumerated valid digit assignments; optimum is {expected}.",
        )
    return VerificationResult(
        "incorrect", "high", "place_value_constraints",
        computed_answer=str(expected),
        evidence=f"Enumerated valid digit assignments; expected optimum {expected}.",
        recommended_fix=f"Replace the claimed optimum with {expected} and update the worked steps.",
    )


