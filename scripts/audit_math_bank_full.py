def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Full AC9 Mathematics exercise-bank audit for Years 7-10."
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--year", type=int, choices=[7, 8, 9, 10], help="Audit a single year level.")
    group.add_argument("--all", action="store_true", help="Audit all years (7-10).")
    parser.add_argument("--strict", action="store_true",
                        help="Exit with code 1 for critical/high hard errors or any definite content error (not advisory/review).")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT_DIR,
                        help=f"Output directory (default: {DEFAULT_OUT_DIR})")
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR,
                        help=f"Data directory (default: {DEFAULT_DATA_DIR})")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    years = list(range(7, 11)) if args.all else [args.year]

    overall_hard_critical = 0
    overall_hard_high = 0
    overall_content_errors = 0
    overall_unverified = 0

    for year in years:
        print(f"\n{'=' * 60}")
        print(f"Auditing Year {year} Mathematics exercise bank...")
        print(f"{'=' * 60}")

        stats = audit_year(year, args.data_dir, args.out)

        print(f"  Items: {stats['total_items']}")
        print(f"  Total issues: {stats['total_issues']}")
        print(f"  Hard errors: {stats['hard_errors_count']} (C:{stats['hard_critical']} H:{stats['hard_high']} M:{stats['hard_medium']} L:{stats['hard_low']})")
        print(f"  Content errors: {stats['content_errors_count']}")
        print(f"  Review needed: {stats['review_needed_count']}")
        print(f"  Advisory: {stats['advisory_count']}")
        print(f"  Maths: verified={stats['maths_verified']} incorrect={stats['maths_incorrect']} likely={stats['maths_likely_issue']} inconclusive={stats['maths_inconclusive']} unsupported={stats['maths_unsupported']}")
        print(f"  Extension: {stats['ext_evaluated']} evaluated (routine={stats['ext_routine']} weak={stats['ext_weak']} adequate={stats['ext_adequate']} strong={stats['ext_strong']})")
        print(f"  Diagrams: {stats['diagram_count']} items, {stats['diagram_hard_errors']} hard errors")
        print(f"  Outputs written to: {args.out}")

        overall_hard_critical += stats["hard_critical"]
        overall_hard_high += stats["hard_high"]
        overall_content_errors += stats["content_errors_count"]
        overall_unverified += stats["maths_unverified"]

    if args.strict:
        if overall_hard_critical > 0 or overall_hard_high > 0 or overall_content_errors > 0:
            print(
                "\nSTRICT MODE: Found "
                f"{overall_hard_critical} critical + {overall_hard_high} high hard errors "
                f"+ {overall_content_errors} content errors. Exiting with code 1."
            )
            return 1
        print("\nSTRICT MODE: Structural and definite-content gates passed.")
        if overall_unverified:
            print(
                f"NOTE: {overall_unverified} items still require deterministic or human maths verification; "
                "see the maths review queue."
            )

    return 0


if __name__ == "__main__":
    sys.exit(main())
