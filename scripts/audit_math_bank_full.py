def evaluate_extension_quality(ex: dict[str, Any]) -> dict[str, Any]:
    """Evaluate extension/AMC quality with detailed scoring dimensions.

    Returns dict with score, classification, and per-dimension breakdown.
    """
    diff = str(ex.get("difficulty", ""))
    comp = str(ex.get("complexity", ""))
    is_extending = diff in {"extending", "AMC"} or comp == "complex_unfamiliar"
    is_amc = diff == "AMC"
    qtype = str(ex.get("question_type", ""))

    if not is_extending:
        return {
            "score": 0, "classification": "not_applicable",
            "dimensions": {}, "amc_flags": [],
        }

    text = combined_text(ex)
    question = str(ex.get("question", ""))
    steps = ex.get("steps") or []
    expected = meta(ex).get("expected_working_steps") or []

    # Dimension 1: multi_step_reasoning (0-2)
    step_count = max(len(steps), len(expected))
    multi_step_score = 0
    if step_count >= 5 or (isinstance(ex.get("sub_parts"), list) and len(ex.get("sub_parts") or []) >= 3):
        multi_step_score = 2
    elif step_count >= 3 or qtype == "multi_part":
        multi_step_score = 1
    # Also check for multi-step language
    if MULTI_STEP_PATTERNS.search(text):
        multi_step_score = min(2, multi_step_score + 1)

    # Dimension 2: non_routine_strategy (0-2)
    non_routine_score = 0
    if NON_ROUTINE_PATTERNS.search(text):
        non_routine_score += 1
    if COGNITIVE_VERB_PATTERNS.search(question):
        non_routine_score += 1
    if ROUTINE_STEM_PATTERNS.search(question) and not NON_ROUTINE_PATTERNS.search(text):
        non_routine_score = max(0, non_routine_score - 1)
    non_routine_score = max(0, min(2, non_routine_score))

    # Dimension 3: unfamiliar_transfer (0-2)
    unfamiliar_score = 0
    if comp == "complex_unfamiliar":
        unfamiliar_score += 1
    if re.search(r"\b(scenario|context|real.world|application|situation|design|create)\b", text, re.I):
        unfamiliar_score += 1
    if re.search(r"\b(modelling|model|apply|application|practical)\b", text, re.I):
        unfamiliar_score = min(2, unfamiliar_score + 1)
    unfamiliar_score = min(2, max(0, unfamiliar_score))

    # Dimension 4: explanation_or_justification (0-1)
    explanation_score = 0
    if qtype in {"reasoning", "multi_part"}:
        explanation_score += 1
    elif re.search(r"\b(explain|justify|reason|why|because|therefore|hence)\b", question, re.I):
        explanation_score += 1
    if str(ex.get("sample_reasoning", "")).strip():
        explanation_score = max(explanation_score, 1)
    explanation_score = min(1, explanation_score)

    # Dimension 5: year_level_fit (0-1)
    year = ex.get("year_level", 7)
    senior_pattern = SENIOR_CONTENT_PATTERNS.get(int(year) if year else 7)
    year_fit_score = 1
    if senior_pattern and senior_pattern.search(text):
        year_fit_score = 0

    # Dimension 6: misconception_or_distractor_quality (0-1)
    misconception_score = 0
    m = meta(ex)
    misconceptions = m.get("common_misconceptions") or m.get("common_misconception") or []
    if isinstance(misconceptions, list) and len(misconceptions) >= 1:
        misconception_score = 1
    elif qtype == "multiple_choice":
        choices = ex.get("choices") or []
        if len(choices) >= 4 and len(set(str(c) for c in choices)) == len(choices):
            misconception_score = 1

    # Dimension 7: self_study_support (0-1)
    self_study_score = 0
    if isinstance(steps, list) and len(steps) >= 2:
        self_study_score += 1
    if isinstance(ex.get("rubric"), dict) and ex["rubric"]:
        self_study_score = max(self_study_score, 1)
    if str(ex.get("sample_reasoning", "")).strip():
        self_study_score = max(self_study_score, 1)
    self_study_score = min(1, self_study_score)

    total = multi_step_score + non_routine_score + unfamiliar_score + explanation_score + year_fit_score + misconception_score + self_study_score

    # Classification
    if total <= 3:
        classification = "routine_mislabeled"
    elif total <= 5:
        classification = "weak_extension"
    elif total <= 7:
        classification = "adequate_extension"
    else:
        classification = "strong_extension"

    # AMC-specific flags
    amc_flags: list[str] = []
    if is_amc:
        if non_routine_score == 0 and multi_step_score <= 1:
            amc_flags.append("routine_calculation_only")
        if senior_pattern and senior_pattern.search(text):
            amc_flags.append("senior_content_beyond_year_level")
        if non_routine_score == 0:
            amc_flags.append("lacks_strategy_or_non_routine_reasoning")
        if classification == "routine_mislabeled":
            amc_flags.append("not_amc_quality")

    return {
        "score": total,
        "classification": classification,
        "dimensions": {
            "multi_step_reasoning": multi_step_score,
            "non_routine_strategy": non_routine_score,
            "unfamiliar_transfer": unfamiliar_score,
            "explanation_or_justification": explanation_score,
            "year_level_fit": year_fit_score,
            "misconception_or_distractor_quality": misconception_score,
            "self_study_support": self_study_score,
        },
        "amc_flags": amc_flags,
    }


