def _answer_matches_number(ex: dict[str, Any], expected: float, tol: float = 0.01) -> bool:
    answer = _answer_text_for_verification(ex)
    for frac in extract_fractions(answer):
        if abs(float(frac) - expected) <= tol:
            return True
    for num, den in re.findall(r"(?<!\d)(-?\d+)\s*/\s*(-?\d+)", answer):
        try:
            d = int(den)
            if d and abs((int(num) / d) - expected) <= tol:
                return True
        except ValueError:
            pass
    return any(abs(n - expected) <= tol for n in extract_numbers(answer))


def _answer_contains_all_numbers(ex: dict[str, Any], expected: list[float], tol: float = 0.01) -> bool:
    answer_nums = extract_numbers(_answer_text_for_verification(ex))
    return all(any(abs(a - e) <= tol for a in answer_nums) for e in expected)


def _verify_area_volume(ex: dict[str, Any]) -> VerificationResult:
    """Verify common Year 8 area, perimeter, circumference and volume tasks."""
    question = str(ex.get("question", ""))
    q = question.lower()
    if re.search(r"\bx\b|\([^)]+\bx", q):
        return VerificationResult("inconclusive", "low", "area_volume",
                                  evidence="Algebraic measurement task requires broader reasoning.")
    if re.search(r"more than (?:its )?width|find the width and length|find width and length", q):
        return VerificationResult("inconclusive", "low", "area_volume",
                                  evidence="Measurement equation task requires broader reasoning.")
    dim_text = re.sub(r"(?:cm|m|km|mm)\s*\$?\s*\^?\s*\{?[23]\}?", "", question, flags=re.I)
    dim_text = re.sub(r"use\s*\\?pi\s*(?:approx|≈)\s*(?:\\frac\{22\}\{7\}|22\s*/\s*7|3\.14)", "", dim_text, flags=re.I)
    nums = extract_numbers(dim_text)
    if not nums:
        return VerificationResult("inconclusive", "low", "area_volume",
                                  evidence="No numeric dimensions found.")

    computed: float | None = None
    label = "area_volume"

    if "composite" in q and "rectangle" in q and "triangle" in q and "area" in q and len(nums) >= 4:
        computed = nums[0] * nums[1] + 0.5 * nums[2] * nums[3]
        label = "composite_area"
    elif "rectangle" in q and "perimeter" in q and "length" in q and "width" in q and len(nums) >= 2:
        computed = 2 * (nums[0] + nums[1])
        label = "rectangle_perimeter"
    elif "rectangle" in q and "area" in q and "length" in q and re.search(r"\b(width|wide)\b", q) and len(nums) >= 2:
        area, length = nums[0], nums[1]
        if length:
            computed = area / length
            label = "rectangle_missing_width"
    elif "triangle" in q and "area" in q and "base" in q and "height" in q and len(nums) >= 2:
        if re.search(r"\bfind the height\b", q) and len(nums) >= 2:
            area, base = nums[0], nums[1]
            if base:
                computed = 2 * area / base
                label = "triangle_missing_height"
        elif len(nums) >= 2:
            computed = 0.5 * nums[0] * nums[1]
            label = "triangle_area"
    elif "trapezium" in q and "area" in q and len(nums) >= 3:
        computed = 0.5 * (nums[0] + nums[1]) * nums[2]
        label = "trapezium_area"
    elif "circumference" in q and "diameter" in q:
        pi = 22 / 7 if "22" in q and "7" in q else 3.14
        d_match = re.search(r"diameter\s*\$?\s*(\d+(?:\.\d+)?)", question, re.I)
        if d_match:
            computed = pi * float(d_match.group(1))
            label = "circle_circumference"
    elif "path" in q and "surround" in q and "radius" in q and len(nums) >= 2:
        pi = 3.14
        r, width = nums[0], nums[1]
        computed = pi * ((r + width) ** 2 - r ** 2)
        label = "annulus_area"
    elif "rectangular prism" in q and "volume" in q and len(nums) >= 3:
        computed = nums[0] * nums[1] * nums[2]
        label = "rectangular_prism_volume"
    elif "triangular prism" in q and "volume" in q and len(nums) >= 3:
        # Common wording gives right-triangle base sides and prism length.
        computed = 0.5 * nums[0] * nums[1] * nums[2]
        label = "triangular_prism_volume"

    if computed is None:
        return VerificationResult("inconclusive", "low", "area_volume",
                                  evidence="No supported direct geometry pattern.")
    if _answer_matches_number(ex, computed, tol=0.05):
        return VerificationResult("verified", "high", label,
            computed_answer=str(computed),
            evidence=f"Computed {label}: {computed}")
    return VerificationResult("likely_issue", "medium", label,
        computed_answer=str(computed),
        evidence=f"Computed {computed}, answer does not contain it.",
        recommended_fix=f"Recheck {label}: {computed}")


def _verify_exponent_laws(ex: dict[str, Any]) -> VerificationResult:
    """Verify direct Year 8 exponent-law simplification/evaluation tasks."""
    question = str(ex.get("question", ""))
    answer = _answer_text_for_verification(ex)
    blocks = re.findall(r"\$([^$]+)\$", question)
    expr = blocks[0] if blocks else question
    norm = _normalise_arithmetic_expression(expr) or expr

    if re.search(r"ratio of the incorrect answer to the correct answer", question, re.I):
        m = re.search(r"\((\d+)\^(\d+)\)\^(\d+)", question)
        if m and re.search(r"\b(add|adds|adding)\b", question, re.I):
            base, e1, e2 = int(m.group(1)), int(m.group(2)), int(m.group(3))
            ratio = Fraction(base ** (e1 + e2), base ** (e1 * e2))
            if ratio in extract_fractions(answer):
                return VerificationResult("verified", "high", "exponent_laws",
                    computed_answer=str(ratio),
                    evidence=f"Incorrect/correct ratio = {base}^{e1 + e2}/{base}^{e1 * e2} = {ratio}")
            return VerificationResult("inconclusive", "low", "exponent_laws",
                evidence="Exponent-law error-analysis ratio not confidently matched.")

    # Numeric exponent expression, including negative exponents.
    wants_power_form = bool(re.search(r"(single power|using (?:the )?(?:exponent|index) laws|simplify)", question, re.I)
                            and re.search(r"\^\{?-?\d+\}?", answer))
    if not wants_power_form and re.fullmatch(r"[0-9+\-*/().\s*]+", norm) and "**" in norm:
        computed = _safe_eval_arithmetic(norm)
        if computed is not None:
            if _answer_matches_number(ex, computed, tol=0.001):
                return VerificationResult("verified", "high", "exponent_laws",
                    computed_answer=str(computed),
                    evidence=f"Evaluated exponent expression = {computed}")
            return VerificationResult("likely_issue", "medium", "exponent_laws",
                computed_answer=str(computed),
                evidence=f"Computed {computed}, answer does not contain it.",
                recommended_fix=f"Recheck exponent expression: {computed}")

    compact_q = re.sub(r"\s+", "", question)
    compact_a = re.sub(r"\s+", "", answer)

    # Same-base multiplication: 2^3 x 2^5 -> 2^8.
    m = re.search(r"([A-Za-z]|\d+)\^(\-?\d+).*?(?:\\times|×|\*|x).*?\1\^(\-?\d+)", compact_q)
    if m:
        base, e1, e2 = m.group(1), int(m.group(2)), int(m.group(3))
        expected_exp = e1 + e2
        if re.search(rf"{re.escape(base)}\^{{?{expected_exp}}}?", compact_a):
            return VerificationResult("verified", "high", "exponent_laws",
                computed_answer=f"{base}^{expected_exp}",
                evidence=f"Same-base multiplication adds exponents: {e1}+{e2}={expected_exp}")
        if base.isdigit() and _answer_matches_number(ex, float(int(base) ** expected_exp), tol=0.001):
            return VerificationResult("verified", "high", "exponent_laws",
                computed_answer=str(int(base) ** expected_exp))

    # Same-base division: 5^7 / 5^4 -> 5^3.
    m = re.search(r"([A-Za-z]|\d+)\^(\-?\d+).*?(?:/|\\div|÷).*?\1\^(\-?\d+)", compact_q)
    if m:
        base, e1, e2 = m.group(1), int(m.group(2)), int(m.group(3))
        expected_exp = e1 - e2
        if re.search(rf"{re.escape(base)}\^{{?{expected_exp}}}?", compact_a):
            return VerificationResult("verified", "high", "exponent_laws",
                computed_answer=f"{base}^{expected_exp}",
                evidence=f"Same-base division subtracts exponents: {e1}-{e2}={expected_exp}")
        if base.isdigit() and _answer_matches_number(ex, float(int(base) ** expected_exp), tol=0.001):
            return VerificationResult("verified", "high", "exponent_laws",
                computed_answer=str(int(base) ** expected_exp))

    # Power of a power followed by multiply: (3^2)^4 x 3^3 -> 3^11.
    m = re.search(r"\((\d+)\^(\-?\d+)\)\^(\-?\d+).*?(?:\\times|×|\*|x).*?\1\^(\-?\d+)", compact_q)
    if m:
        base, e1, e2, e3 = m.group(1), int(m.group(2)), int(m.group(3)), int(m.group(4))
        expected_exp = e1 * e2 + e3
        if re.search(rf"{re.escape(base)}\^{{?{expected_exp}}}?", compact_a):
            return VerificationResult("verified", "high", "exponent_laws",
                computed_answer=f"{base}^{expected_exp}")

    return VerificationResult("inconclusive", "low", "exponent_laws",
                              evidence="No supported exponent-law pattern.")


def _verify_function_table(ex: dict[str, Any]) -> VerificationResult:
    """Verify simple function tables and gradients from two points."""
    question = str(ex.get("question", ""))
    answer = str(ex.get("answer", ""))
    q_norm = strip_latex(question)

    formula = re.search(r"y\s*=\s*([+-]?\s*\d+(?:\.\d+)?)?\s*x\s*([+-]\s*\d+(?:\.\d+)?)?", q_norm, re.I)
    x_list = re.search(r"x\s*=\s*([-?\d,\s]+)", q_norm, re.I)
    if formula and x_list:
        m = float(formula.group(1).replace(" ", "")) if formula.group(1) else 1.0
        b = float(formula.group(2).replace(" ", "")) if formula.group(2) else 0.0
        xs = [float(x) for x in re.findall(r"-?\d+", x_list.group(1))]
        expected = [(x, m * x + b) for x in xs]
        ans_pairs = [(float(a), float(bv)) for a, bv in re.findall(r"\((-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)\)", answer)]
        if expected and all(any(abs(ax - x) < 0.001 and abs(ay - y) < 0.001 for ax, ay in ans_pairs) for x, y in expected):
            return VerificationResult("verified", "high", "function_table",
                computed_answer=str(expected),
                evidence="All table/coordinate values match the linear rule.")
        if ans_pairs:
            return VerificationResult("likely_issue", "medium", "function_table",
                computed_answer=str(expected),
                evidence=f"Expected {expected}, answer has {ans_pairs}",
                recommended_fix=f"Recheck function table: {expected}")

    if re.search(r"\bgradient|slope\b", question, re.I):
        coords = [(float(a), float(b)) for a, b in re.findall(r"\((-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)\)", question)]
        if len(coords) >= 2:
            (x1, y1), (x2, y2) = coords[0], coords[1]
            if x2 != x1:
                grad = (y2 - y1) / (x2 - x1)
                if _answer_matches_number(ex, grad, tol=0.001):
                    return VerificationResult("verified", "high", "gradient",
                        computed_answer=str(grad),
                        evidence=f"Gradient = ({y2}-{y1})/({x2}-{x1}) = {grad}")
                return VerificationResult("likely_issue", "medium", "gradient",
                    computed_answer=str(grad),
                    evidence=f"Computed gradient {grad}, answer does not contain it.",
                    recommended_fix=f"Recheck gradient: {grad}")

    sub = _verify_formula_substitution(ex)
    if sub.status != "inconclusive":
        return sub
    return VerificationResult("inconclusive", "low", "function_table",
                              evidence="No supported function-table pattern.")


def _verify_similarity_congruence(ex: dict[str, Any]) -> VerificationResult:
    """Verify direct similar-triangle numeric side/area questions."""
    question = str(ex.get("question", ""))
    q = question.lower()
    nums = extract_numbers(question)

    if "similar triangle" in q and "perimeter" in q and len(nums) >= 4:
        sides = nums[:3]
        target_perimeter = nums[3]
        original = sum(sides)
        if original:
            scale = target_perimeter / original
            expected = [s * scale for s in sides]
            if _answer_contains_all_numbers(ex, expected, tol=0.01):
                return VerificationResult("verified", "high", "similarity",
                    computed_answer=str(expected),
                    evidence=f"Scale factor {scale}; sides {expected}")
            return VerificationResult("likely_issue", "medium", "similarity",
                computed_answer=str(expected),
                evidence=f"Expected similar sides {expected}.",
                recommended_fix=f"Recheck similar-triangle scale factor: {scale}")

    if "similar" in q and len(nums) >= 4 and re.search(r"\b(find|qr|pr|side)\b", q):
        # Pattern: first triangle has three sides, corresponding first side in
        # second triangle is given. Compute the remaining two.
        sides = nums[:3]
        known = nums[3]
        if sides[0]:
            scale = known / sides[0]
            expected = [sides[1] * scale, sides[2] * scale]
            if _answer_contains_all_numbers(ex, expected, tol=0.01):
                return VerificationResult("verified", "high", "similarity",
                    computed_answer=str(expected),
                    evidence=f"Scale factor {scale}; missing sides {expected}")

    if re.search(r"\bsame side lengths\b|\bsss\b", q) and "yes" in str(ex.get("answer", "")).lower():
        return VerificationResult("verified", "medium", "congruence",
                                  evidence="SSS/same side lengths imply congruence.")
    if "are they similar" in q and len(nums) >= 6:
        a = nums[:3]
        b = nums[3:6]
        ratios = [a[i] / b[i] for i in range(3) if b[i] != 0]
        if len(ratios) == 3 and max(ratios) - min(ratios) < 0.001 and "yes" in str(ex.get("answer", "")).lower():
            return VerificationResult("verified", "high", "similarity",
                                      evidence=f"Matching side ratios: {ratios}")

    return VerificationResult("inconclusive", "low", "similarity",
                              evidence="No supported direct similarity/congruence pattern.")


def _verify_probability_tree(ex: dict[str, Any]) -> VerificationResult:
    """Verify common two-stage probability/tree-diagram tasks."""
    question = str(ex.get("question", ""))
    q = question.lower()
    computed: Fraction | int | None = None

    if re.search(r"coin.*twice|tossed twice|flipped twice", q) and re.search(r"list all outcomes|sample space", q):
        answer = str(ex.get("answer", "")).upper()
        if all(out in answer for out in ["HH", "HT", "TH", "TT"]):
            return VerificationResult("verified", "high", "probability_tree",
                                      evidence="Two coin tosses list HH, HT, TH, TT.")

    if "coin" in q and re.search(r"\bdie\b|six-sided die", q) and re.search(r"how many|sample space|size", q):
        computed = 12
    elif "spinner" in q and "spin twice" in q and "same" in q:
        sections = extract_numbers(question)
        if sections:
            computed = Fraction(1, int(sections[0]))
    elif "bag" in q and "different colour" in q and len(extract_numbers(question)) >= 2:
        a, b = [int(n) for n in extract_numbers(question)[:2]]
        total = a + b
        if total > 1:
            computed = Fraction(2 * a * b, total * (total - 1))
    elif re.search(r"one boy, one girl", q) and len(extract_numbers(question)) >= 2:
        boys, girls = [int(n) for n in extract_numbers(question)[:2]]
        total = boys + girls
        computed = Fraction(boys * girls, total * (total - 1) // 2)
    elif "deck" in q and "both" in q and "aces" in q:
        computed = Fraction(4, 52) * Fraction(3, 51)
    elif "at least one red" in q and "replacement" in q and len(extract_numbers(question)) >= 2:
        red, other = [int(n) for n in extract_numbers(question)[:2]]
        total = red + other
        computed = 1 - Fraction(other, total) ** 2
    elif "both are red" in q and "without replacement" in q and len(extract_numbers(question)) >= 2:
        red, other = [int(n) for n in extract_numbers(question)[:2]]
        total = red + other
        computed = Fraction(red, total) * Fraction(red - 1, total - 1)

    if computed is None:
        base = _verify_probability(ex)
        if base.status != "inconclusive":
            return base
        return VerificationResult("inconclusive", "low", "probability_tree",
                                  evidence="No supported two-stage probability pattern.")

    expected = float(computed)
    if _answer_matches_number(ex, expected, tol=0.001):
        return VerificationResult("verified", "high", "probability_tree",
            computed_answer=str(computed),
            evidence=f"Computed probability/sample-space value = {computed}")
    return VerificationResult("likely_issue", "medium", "probability_tree",
        computed_answer=str(computed),
        evidence=f"Computed {computed}, answer does not contain it.",
        recommended_fix=f"Recheck probability: {computed}")


