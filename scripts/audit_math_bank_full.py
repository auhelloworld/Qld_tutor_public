def write_human_review_queue(issues: list[IssueFlag], out_path: Path) -> None:
    """Write human_review_queue.csv sorted by severity and confidence."""
    # Filter for items needing human review
    review_items = [i for i in issues if i.category != "advisory"]

    severity_order = {"critical": 4, "high": 3, "medium": 2, "low": 1}
    confidence_order = {"high": 3, "medium": 2, "low": 1}
    # Sort by severity (desc) then confidence (desc) then exercise_id for stable order
    review_items.sort(
        key=lambda x: (
            severity_order.get(x.severity, 0),
            confidence_order.get(x.confidence, 0),
        ),
        reverse=True,
    )

    fields = ["exercise_id", "category", "severity", "confidence", "code",
              "message", "evidence", "recommended_fix", "validator"]
    with out_path.open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        for item in review_items:
            writer.writerow(asdict(item))


